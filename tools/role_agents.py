"""Role contracts and native host adapters; no model calls or background execution."""
import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from tools.storage import commit, confined, consistent_read, digest, lock

CATALOG = ROOT / "skills/ieum/references/roles.json"
COMMON = ROOT / "skills/ieum/references/COLLABORATION.md"


def catalog():
    value = json.loads(CATALOG.read_text(encoding="utf-8"))
    if not isinstance(value, dict) or value.get("schema_version") != 1 or not isinstance(value.get("roles"), list) or not value["roles"]:
        raise ValueError("역할 카탈로그 형식이 잘못되었습니다.")
    ids, aliases = set(), set()
    fields = {"id", "label", "group", "aliases", "mission", "inputs", "outputs", "checks", "boundaries", "next_roles", "review_only"}
    for role in value["roles"]:
        if not isinstance(role, dict) or set(role) != fields:
            raise ValueError("역할 계약의 필드가 잘못되었습니다.")
        if any(not isinstance(role[k], str) or not role[k].strip() for k in ("id", "label", "group", "mission")):
            raise ValueError("역할 이름·책임이 필요합니다.")
        if not re.fullmatch(r"[a-z][a-z0-9]*(?:-[a-z0-9]+)*", role["id"]) or role["id"] in ids:
            raise ValueError("역할 ID 중복 또는 잘못된 이름입니다.")
        ids.add(role["id"])
        if type(role["review_only"]) is not bool:
            raise ValueError("검토 전용 여부가 잘못되었습니다.")
        for key in ("aliases", "inputs", "outputs", "checks", "boundaries", "next_roles"):
            if not isinstance(role[key], list) or not role[key] or any(not isinstance(x, str) or not x.strip() for x in role[key]):
                raise ValueError("역할 계약의 목록이 잘못되었습니다.")
        for key in {alias.casefold() for alias in [role["id"], role["label"], *role["aliases"]]}:
            if key in aliases:
                raise ValueError("역할 별칭이 중복되었습니다.")
            aliases.add(key)
    if any(target not in ids for r in value["roles"] for target in r["next_roles"]):
        raise ValueError("인수인계 대상 역할이 없습니다.")
    return value["roles"]


def resolve(name):
    if not isinstance(name, str) or not name.strip():
        raise ValueError("역할 이름이 필요합니다.")
    name = name.strip().casefold()
    if name.startswith("ieum-"):
        name = name[5:]
    for role in catalog():
        if name in {x.casefold() for x in [role["id"], role["label"], *role["aliases"]]}:
            return role
    raise ValueError(f"알 수 없는 역할: {name}. list로 지원 역할을 확인하세요.")


def prompt(name):
    role = resolve(name)
    blocks = [f"# 이음 · {role['label']}\n\n{role['mission']}", COMMON.read_text(encoding="utf-8").strip()]
    for key, title in (("inputs", "필수 입력"), ("outputs", "역할 산출물"), ("checks", "완료 검증"), ("boundaries", "책임 경계")):
        blocks.append("## " + title + "\n\n" + "\n".join("- " + line for line in role[key]))
    blocks.append("## 다음 역할 후보\n\n" + ", ".join(role["next_roles"]) + ". 실제 전달은 상위 조율자가 입력·경로·수용 기준을 확인한 뒤 수행한다.")
    if role["review_only"]:
        blocks.append("읽기 검토 전용이다. 파일·원장 수정과 상태 변경 명령은 금지한다. 소스·diff·로그를 읽는 비변경 조회 명령은 호스트가 허용하는 도구로 사용할 수 있다. 발견 사항을 상위 조율자에게 반환한다.")
    return "\n\n".join(blocks) + "\n"


def render_claude(role):
    metadata = {"name": "ieum-" + role["id"], "description": role["label"] + ". " + role["mission"], "model": "inherit"}
    if role["review_only"]:
        metadata["tools"] = "Read, Glob, Grep"
    header = "\n".join(key + ": " + json.dumps(value, ensure_ascii=False) for key, value in metadata.items())
    return "---\n" + header + "\n---\n\n" + prompt(role["id"])


def render_codex(role):
    # JSON basic strings are also valid TOML strings, including escaped newlines.
    metadata = {"name": "ieum-" + role["id"], "description": role["label"] + ". " + role["mission"], "developer_instructions": prompt(role["id"])}
    return "# Generated by tools/role_agents.py; inherits parent model and permissions.\n" + "\n".join(key + " = " + json.dumps(value, ensure_ascii=False) for key, value in metadata.items()) + "\n"


def generated_files():
    return {"agents/ieum-" + role["id"] + ".md": render_claude(role).encode("utf-8") for role in catalog()}


def build(check=False):
    files = generated_files()
    stale = [name for name, content in files.items() if not (ROOT / name).is_file() or (ROOT / name).read_bytes() != content]
    stale.extend(sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "agents").glob("ieum-*.md") if p.relative_to(ROOT).as_posix() not in files))
    if check:
        return {"ready": not stale, "role_count": len(files), "stale": stale}
    if any((ROOT / "agents").glob("ieum-*.md")):
        extra = [p for p in (ROOT / "agents").glob("ieum-*.md") if p.relative_to(ROOT).as_posix() not in files]
        if extra:
            raise ValueError("폐기된 역할 파일을 검토한 뒤 제거하세요. 자동 삭제하지 않습니다.")
    (ROOT / "agents").mkdir(exist_ok=True)
    for name, content in files.items():
        (ROOT / name).write_bytes(content)
    return {"ready": True, "role_count": len(files), "written": len(stale)}


def project_root(folder):
    from tools import starter
    root, data = starter.load_project(folder)
    if root == ROOT or root.is_relative_to(ROOT / "skills") or root.is_relative_to(ROOT / "blueprint"):
        raise ValueError("플러그인·기본형이 아닌 실제 고객 프로젝트를 선택하세요.")
    return root, data


def adapter_files(host):
    if host == "codex":
        return {".codex/agents/ieum-" + role["id"] + ".toml": render_codex(role).encode("utf-8") for role in catalog()}
    if host == "claude":
        return {".claude/skills/ieum/SKILL.md": (ROOT / "skills/ieum/references/claude-shortcut.md").read_text(encoding="utf-8").encode("utf-8")}
    raise ValueError("지원하지 않는 호스트입니다.")


def codex_preview(folder):
    root, _ = project_root(folder)
    return _adapter_preview(root, "codex")


def claude_preview(folder):
    root, _ = project_root(folder)
    return _adapter_preview(root, "claude")


@consistent_read
def _adapter_preview(folder, host):
    from tools import lifecycle
    root, data = project_root(folder)
    files = adapter_files(host)
    previous, conflicts, changes = {}, [], []
    for name, content in files.items():
        target = confined(root, name)
        if target.exists() and not target.is_file():
            raise ValueError("설정 경로가 일반 파일이 아닙니다: " + name)
        current = target.read_bytes() if target.is_file() else None
        previous[name] = digest(current) if current is not None else None
        if current is not None and current != content:
            conflicts.append(name)
        elif current is None:
            changes.append(name)
    # A legacy local command can compete for the same /ieum name.
    collisions = {}
    if host == "claude":
        legacy = ".claude/commands/ieum.md"
        target = confined(root, legacy)
        if target.exists():
            if not target.is_file():
                raise ValueError("같은 이름의 명령 경로가 일반 파일이 아닙니다.")
            conflicts.append(legacy)
            collisions[legacy] = digest(target.read_bytes())
    events = lifecycle.events(root)
    counts = {"role_count": len(files)} if host == "codex" else {"alias_count": len(files), "command": "/ieum", "collision_sha256": collisions}
    notice = ("프로젝트별 역할 설정만 추가합니다. 기존 파일·config.toml·사용자 전역 설정은 덮어쓰지 않습니다. 새 세션에서 로딩과 실제 실행을 별도 확인하세요."
              if host == "codex" else "이 고객 프로젝트에 /ieum 별칭을 추가합니다. 해당 프로젝트 폴더를 Claude Code에서 열고 명령 목록을 확인하세요. 플러그인 ID·전역 설정·기존 명령은 변경하지 않습니다. 파일 추가만으로 로딩 성공이라 하지 않습니다.")
    return {"kind": "ieum_codex_agents" if host == "codex" else "ieum_claude_alias", "project_id": data["project_id"],
            "expected_revision": events[-1]["revision"] if events else None,
            "current_sha256": previous, "template_sha256": {name: digest(content) for name, content in files.items()},
            "changes": changes, "conflicts": conflicts, **counts, "notice": notice}


def codex_install(folder, payload, actor="agent"):
    return _adapter_install(folder, payload, "codex", actor)


def claude_install(folder, payload, actor="agent"):
    return _adapter_install(folder, payload, "claude", actor)


def _adapter_install(folder, payload, host, actor):
    from tools import lifecycle
    root, _ = project_root(folder)
    with lock(root):
        fresh = _adapter_preview(root, host)
        if not isinstance(payload, dict) or payload != fresh:
            raise ValueError("설치 미리보기가 변경되었습니다. 호스트의 preview를 다시 확인하세요.")
        if fresh["conflicts"]:
            raise ValueError("기존 역할 또는 명령 설정이 다릅니다. 사용자 변경을 보존하고 충돌 파일을 먼저 조율하세요: " + ", ".join(fresh["conflicts"]))
        counts = {key: fresh[key] for key in ("role_count", "alias_count", "command") if key in fresh}
        if not fresh["changes"]:
            return {"unchanged": True, **counts, "host_loaded": False}
        contents = adapter_files(host)
        if {name: digest(content) for name, content in contents.items()} != fresh["template_sha256"]:
            raise ValueError("설치 중 역할 또는 명령 원천이 변경되었습니다. preview를 다시 확인하세요.")
        changes = {name: contents[name] for name in fresh["changes"]}
        action = "ieum-agents-install" if host == "codex" else "ieum-alias-install"
        revision = lifecycle.add_event(root, changes, action, actor, {"host": host, "paths": fresh["changes"]})
        commit(root, changes)
        return {"unchanged": False, "revision": revision, "written": fresh["changes"], **counts, "host_loaded": False, "notice": fresh["notice"]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("list")
    show = commands.add_parser("show")
    show.add_argument("role")
    make = commands.add_parser("build")
    make.add_argument("--check", action="store_true")
    for host in ("codex", "claude"):
        preview = commands.add_parser(host + "-preview")
        preview.add_argument("project")
        install = commands.add_parser(host + "-install")
        install.add_argument("project")
        install.add_argument("--file", type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.command == "list":
            result = {"roles": [{k: role[k] for k in ("id", "label", "group", "aliases")} for role in catalog()]}
        elif args.command == "show":
            print(prompt(args.role))
            return 0
        elif args.command == "build":
            result = build(args.check)
        elif args.command in {"codex-preview", "claude-preview"}:
            result = {"codex-preview": codex_preview, "claude-preview": claude_preview}[args.command](args.project)
        else:
            if args.file.stat().st_size > 1024 * 1024:
                raise ValueError("설치 요청 파일 크기 제한 초과")
            installer = {"codex-install": codex_install, "claude-install": claude_install}[args.command]
            result = installer(args.project, json.loads(args.file.read_text(encoding="utf-8-sig")))
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0 if result.get("ready", True) else 1
    except (OSError, ValueError, KeyError) as exc:
        print(json.dumps({"error": str(exc)}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
